#!/usr/bin/env bash
# Regenerates addons/godot_mcp/core/export_defaults.cfg: every export option of every
# built-in platform with its default value, exactly as the Godot editor writes them to
# export_presets.cfg. export.preset_set uses it when it creates a preset, so documented
# option keys (e.g. "binary_format/embed_pck") can be set right away, with or without the
# editor running (there is no script API for a platform's options outside the editor).
#
# How: a throwaway project with one minimal preset per platform and a generator plugin
# (gen-export-defaults/dump_plugin.gd) that makes a headless editor fill in and save all
# options; gen-export-defaults/convert.gd then regroups them by platform.
#
# Rerun after upgrading the Godot version the addon targets, and commit the result.
# Usage: GODOT=/path/to/godot scripts/gen-export-defaults.sh
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
here="$repo_root/scripts/gen-export-defaults"
out="$repo_root/addons/godot_mcp/core/export_defaults.cfg"
GODOT="${GODOT:-godot}"

work="$(mktemp -d "${TMPDIR:-/tmp}/godot-mcp-export-defaults.XXXXXX")"
trap 'rm -rf "$work"' EXIT

mkdir -p "$work/addons/dump"
cp "$here/dump_plugin.gd" "$work/addons/dump/plugin.gd"
cp "$here/convert.gd" "$work/convert.gd"
cat >"$work/addons/dump/plugin.cfg" <<'EOF'
[plugin]
name="export defaults dump"
description=""
author=""
version="1"
script="plugin.gd"
EOF
cat >"$work/project.godot" <<'EOF'
config_version=5

[application]
config/name="export defaults"

[editor_plugins]
enabled=PackedStringArray("res://addons/dump/plugin.cfg")
EOF

# One preset per platform (names as EditorExportPlatform::get_name returns them).
i=0
: >"$work/export_presets.cfg"
for platform in "Linux" "Windows Desktop" "macOS" "Android" "iOS" "visionOS" "Web"; do
	cat >>"$work/export_presets.cfg" <<EOF
[preset.$i]

name="$platform"
platform="$platform"

[preset.$i.options]

custom_template/debug=""

EOF
	i=$((i + 1))
done

"$GODOT" --headless --path "$work" --import >/dev/null 2>&1 || true
timeout 120 "$GODOT" --headless --editor --path "$work" 2>&1 | grep -E "export-defaults|ERROR" || true
"$GODOT" --headless --path "$work" --script res://convert.gd -- "$out"
{
	printf '; Generated by scripts/gen-export-defaults.sh with %s. Do not edit by hand.\n' "$("$GODOT" --version | tr -d '\r')"
	printf '; Every export option of each platform and its default, as the editor writes them.\n\n'
	cat "$out"
} >"$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
