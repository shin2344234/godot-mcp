#!/usr/bin/env bash
# Regenerates addons/godot_mcp/core/import_defaults.cfg: every option of every built-in
# importer the addon can switch to (import_ops.gd IMPORTERS_BY_EXT), with its default value,
# exactly as Godot writes them to a fresh .import file. import.get uses it to show only the
# options that differ from the defaults (a texture has ~26 options; listing all of them on
# every call cost ~600 tokens, MCP_TEST_LOG Phase A). No script API exposes an importer's
# options (ResourceImporter is not scriptable), so they are captured from a real import.
#
# How: a throwaway project with one file per importer and a .import file naming that
# importer (gen-import-defaults/gen.gd make), `godot --headless --import`, then gen.gd
# convert collects each file's [params] into one section per importer.
#
# Rerun after upgrading the Godot version the addon targets, and commit the result.
# Usage: GODOT=/path/to/godot scripts/gen-import-defaults.sh
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
here="$repo_root/scripts/gen-import-defaults"
out="$repo_root/addons/godot_mcp/core/import_defaults.cfg"
GODOT="${GODOT:-godot}"

work="$(mktemp -d "${TMPDIR:-/tmp}/godot-mcp-import-defaults.XXXXXX")"
trap 'rm -rf "$work"' EXIT

cp "$here/gen.gd" "$work/gen.gd"
cat >"$work/project.godot" <<'EOF'
config_version=5

[application]
config/name="import defaults"
EOF

"$GODOT" --headless --path "$work" --script res://gen.gd -- make
"$GODOT" --headless --path "$work" --import >/dev/null 2>&1 || true
"$GODOT" --headless --path "$work" --script res://gen.gd -- convert "$out"
{
	printf '; Generated by scripts/gen-import-defaults.sh with %s. Do not edit by hand.\n' "$("$GODOT" --version | tr -d '\r')"
	printf '; Every option of each importer and its default, as Godot writes them to a new .import file.\n\n'
	cat "$out"
} >"$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
